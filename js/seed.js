export function seedText(minorName) {
  const name = String(minorName || '');
  for (let i = 0; i < SEEDS.length; i++) {
    if (SEEDS[i].match.some(function (m) { return name.indexOf(m) !== -1; })) return SEEDS[i].text;
  }
  return '';
}
